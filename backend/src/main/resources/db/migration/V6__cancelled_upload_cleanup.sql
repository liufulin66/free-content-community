CREATE TABLE media_upload_cleanup (
    id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    owner_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    upload_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    asset_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    storage_key VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    signer_id CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    state VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    attempt_count INT NOT NULL DEFAULT 0,
    available_at DATETIME(6) NOT NULL,
    lease_token VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    lease_until DATETIME(6) NULL,
    last_error_code VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_upload_cleanup_upload (upload_id),
    KEY idx_upload_cleanup_due (state, available_at, id),
    KEY idx_upload_cleanup_lease (state, lease_until),
    CONSTRAINT fk_upload_cleanup_owner FOREIGN KEY (owner_id) REFERENCES app_user (id),
    CONSTRAINT fk_upload_cleanup_upload FOREIGN KEY (upload_id) REFERENCES media_upload_session (id),
    CONSTRAINT fk_upload_cleanup_asset FOREIGN KEY (asset_id) REFERENCES media_asset (id),
    CONSTRAINT chk_upload_cleanup_state CHECK (state IN ('PENDING','RUNNING','SUCCEEDED','FAILED')),
    CONSTRAINT chk_upload_cleanup_attempts CHECK (attempt_count >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
