CREATE TABLE media_processing_task (
    id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    owner_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    upload_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    asset_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    type VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    state VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    progress_percent INT NOT NULL DEFAULT 0,
    retryable BOOLEAN NOT NULL DEFAULT FALSE,
    error_code VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NULL,
    error_message VARCHAR(500) NULL,
    retry_of_task_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    storage_key VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    signer_id CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    object_etag VARCHAR(200) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    object_version_id VARCHAR(1024) CHARACTER SET ascii COLLATE ascii_bin NULL,
    object_size_bytes BIGINT NOT NULL,
    object_content_type VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    object_last_modified DATETIME(6) NOT NULL,
    expected_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    KEY idx_media_processing_owner (owner_id, created_at),
    KEY idx_media_processing_upload (upload_id),
    KEY idx_media_processing_state (state, created_at),
    CONSTRAINT fk_media_processing_owner FOREIGN KEY (owner_id) REFERENCES app_user (id),
    CONSTRAINT fk_media_processing_upload FOREIGN KEY (upload_id) REFERENCES media_upload_session (id),
    CONSTRAINT fk_media_processing_asset FOREIGN KEY (asset_id) REFERENCES media_asset (id),
    CONSTRAINT fk_media_processing_retry FOREIGN KEY (retry_of_task_id) REFERENCES media_processing_task (id),
    CONSTRAINT chk_media_processing_type CHECK (type = 'MEDIA_PROCESSING'),
    CONSTRAINT chk_media_processing_state CHECK (state IN ('PENDING','RUNNING','SUCCEEDED','FAILED','CANCELLED')),
    CONSTRAINT chk_media_processing_progress CHECK (progress_percent BETWEEN 0 AND 100),
    CONSTRAINT chk_media_processing_size CHECK (object_size_bytes BETWEEN 1 AND 9007199254740991)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE media_upload_completion_request (
    id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    owner_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    key_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    fingerprint CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    state VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    upload_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    task_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    lease_token VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    lease_until DATETIME(6) NULL,
    expires_at DATETIME(6) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_media_completion_scope (owner_id, key_hash),
    KEY idx_media_completion_expiry (expires_at),
    CONSTRAINT fk_media_completion_owner FOREIGN KEY (owner_id) REFERENCES app_user (id),
    CONSTRAINT fk_media_completion_upload FOREIGN KEY (upload_id) REFERENCES media_upload_session (id),
    CONSTRAINT fk_media_completion_task FOREIGN KEY (task_id) REFERENCES media_processing_task (id),
    CONSTRAINT chk_media_completion_state CHECK (state IN ('PROCESSING','SUCCEEDED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
