CREATE TABLE media_asset (
    id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    owner_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    scene VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    declared_content_type VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    declared_size_bytes BIGINT NOT NULL,
    expected_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    storage_key VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    state VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    actual_content_type VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NULL,
    actual_size_bytes BIGINT NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_media_asset_storage_key (storage_key),
    KEY idx_media_asset_owner (owner_id, created_at),
    CONSTRAINT fk_media_asset_owner FOREIGN KEY (owner_id) REFERENCES app_user (id),
    CONSTRAINT chk_media_asset_scene CHECK (scene IN ('AVATAR','CONTENT_IMAGE','CONTENT_VIDEO','REPORT_ATTACHMENT')),
    CONSTRAINT chk_media_asset_state CHECK (state IN ('WAITING_UPLOAD','PROCESSING','READY','FAILED')),
    CONSTRAINT chk_media_asset_size CHECK (declared_size_bytes BETWEEN 1 AND 9007199254740991),
    CONSTRAINT chk_media_asset_actual_size CHECK (actual_size_bytes IS NULL OR actual_size_bytes >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE media_upload_session (
    id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    asset_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    owner_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    storage_key VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    content_type VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    state VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    version INT NOT NULL DEFAULT 1,
    signature_at DATETIME(6) NOT NULL,
    signature_ttl_seconds INT NOT NULL,
    signer_id CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    expires_at DATETIME(6) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_media_upload_asset (asset_id),
    KEY idx_media_upload_owner (owner_id, created_at),
    KEY idx_media_upload_expiry (state, expires_at),
    CONSTRAINT fk_media_upload_asset FOREIGN KEY (asset_id) REFERENCES media_asset (id),
    CONSTRAINT fk_media_upload_owner FOREIGN KEY (owner_id) REFERENCES app_user (id),
    CONSTRAINT chk_media_upload_state CHECK (state IN ('UPLOADING','COMPLETED','CANCELLED','EXPIRED')),
    CONSTRAINT chk_media_upload_version CHECK (version >= 1),
    CONSTRAINT chk_media_upload_signature_ttl CHECK (signature_ttl_seconds BETWEEN 1 AND 604800)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE media_upload_request (
    id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    owner_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    key_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    fingerprint CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    state VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    upload_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    lease_token VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    lease_until DATETIME(6) NULL,
    expires_at DATETIME(6) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_media_upload_request_scope (owner_id, key_hash),
    KEY idx_media_upload_request_expiry (expires_at),
    CONSTRAINT fk_media_request_owner FOREIGN KEY (owner_id) REFERENCES app_user (id),
    CONSTRAINT fk_media_request_upload FOREIGN KEY (upload_id) REFERENCES media_upload_session (id),
    CONSTRAINT chk_media_request_state CHECK (state IN ('PROCESSING','SUCCEEDED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
